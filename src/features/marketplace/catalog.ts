export const catalogImage = (id: string, detail = false) =>
  "/marketplace/catalog/" + id + (detail ? "-detail" : "") + ".webp";
export const products: Product[] = listings.map(
  (
    [id, name, sellerId, kind, category, price, material, dimensions, description, specs, days],
    index,
  ) => ({
    id,
    name,
    sellerId,
    kind,
    category: categoryIndex[category],
    price,
    material,
    dimensions,
    description,
    specs,
    days,
    license: kind === "digital" ? DESIGN_LICENSE : "",
    formats: kind === "digital" ? ["OBJ", "MTL", "TXT"] : [],
    asset:
      kind === "digital"
        ? { src: "/marketplace/downloads/" + id + ".zip", name: id + ".zip" }
        : undefined,
    images: [
      { name: "Vista principal", src: catalogImage(id) },
      { name: "Vista de detalle", src: catalogImage(id, true) },
    ],
    badge:
      kind !== "digital" && category === 9
        ? "Personalizable"
        : kind === "physical" && [1, 7, 8].includes(category)
          ? "Fabricado bajo pedido"
          : undefined,
    createdAt: new Date(Date.UTC(2026, 10, 21 - index)).toISOString(),
    featured: index < 8,
  }),
);

